package com.kitchenai.membership;

import static org.junit.jupiter.api.Assertions.*;
import java.util.UUID;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

class EntitlementServiceTest {
  private JdbcTemplate jdbc;
  private EntitlementService service;

  @BeforeEach
  void setUp() {
    JdbcDataSource dataSource = new JdbcDataSource();
    dataSource.setURL("jdbc:h2:mem:membership" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1");
    jdbc = new JdbcTemplate(dataSource);
    jdbc.execute("CREATE TABLE user_membership (user_id UUID PRIMARY KEY, tier VARCHAR(20), billing_interval VARCHAR(20), status VARCHAR(30), paid_until TIMESTAMP WITH TIME ZONE, created_at TIMESTAMP, updated_at TIMESTAMP)");
    jdbc.execute("CREATE TABLE recipe_quota_usage (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL, period_key VARCHAR(80) NOT NULL, used_count INT NOT NULL, updated_at TIMESTAMP, UNIQUE(user_id, period_key))");
    service = new EntitlementService(jdbc);
  }

  @Test
  void freeAllowsThreeLifetimeReservationsAndReleasesFailures() {
    UUID userId = UUID.randomUUID();
    assertNotNull(service.reserve(userId));
    EntitlementService.QuotaReservation failedAttempt = service.reserve(userId);
    assertNotNull(failedAttempt);
    service.release(failedAttempt);
    assertNotNull(service.reserve(userId));
    assertNotNull(service.reserve(userId));
    assertNull(service.reserve(userId));
  }

  @Test
  void chefTierFailsClosed() {
    UUID userId = UUID.randomUUID();
    jdbc.update("INSERT INTO user_membership(user_id,tier,billing_interval,status,created_at,updated_at) VALUES (?, 'CHEF','NONE','ACTIVE',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)", userId);
    assertNull(service.reserve(userId));
  }
}
