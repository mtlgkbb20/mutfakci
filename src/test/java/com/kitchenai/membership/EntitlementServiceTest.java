package com.kitchenai.membership;

import static org.junit.jupiter.api.Assertions.*;
import java.sql.Timestamp;
import java.time.Duration;
import java.time.Instant;
import java.util.*;
import java.util.concurrent.*;
import java.util.concurrent.atomic.AtomicInteger;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.annotation.AnnotationTransactionAttributeSource;
import org.springframework.transaction.interceptor.TransactionInterceptor;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;

class EntitlementServiceTest {
  private JdbcTemplate jdbc;
  private EntitlementService service;
  private JdbcDataSource dataSource;

  @BeforeEach
  void setUp() {
    dataSource = new JdbcDataSource();
    dataSource.setURL("jdbc:h2:mem:membership" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=10000");
    jdbc = new JdbcTemplate(dataSource);
    jdbc.execute("CREATE TABLE user_membership (user_id UUID PRIMARY KEY, tier VARCHAR(20), billing_interval VARCHAR(20), status VARCHAR(30), paid_until TIMESTAMP WITH TIME ZONE, created_at TIMESTAMP, updated_at TIMESTAMP)");
    jdbc.execute("CREATE TABLE recipe_quota_usage (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id UUID NOT NULL, period_key VARCHAR(80) NOT NULL, used_count INT NOT NULL, updated_at TIMESTAMP, UNIQUE(user_id, period_key))");
    jdbc.execute("CREATE TABLE gamification_reward_grant (id UUID PRIMARY KEY, user_id UUID NOT NULL, reward_type VARCHAR(40) NOT NULL, source_key VARCHAR(160) NOT NULL, status VARCHAR(20) NOT NULL, issued_at TIMESTAMP WITH TIME ZONE NOT NULL, expires_at TIMESTAMP WITH TIME ZONE NOT NULL, redeemed_at TIMESTAMP WITH TIME ZONE, reserved_at TIMESTAMP WITH TIME ZONE)");
    service = new EntitlementService(jdbc);
  }

  @Test
  void freeAllowsThreeLifetimeReservationsAndReleasesFailures() {
    UUID userId = UUID.randomUUID();
    assertNotNull(service.reserve(userId));
    EntitlementService.QuotaReservation failedAttempt = service.reserve(userId);
    assertNotNull(failedAttempt);
    service.release(failedAttempt);
    assertNotNull(service.reserve(userId));
    assertNotNull(service.reserve(userId));
    assertNull(service.reserve(userId));
  }

  @Test
  void chefTierFailsClosed() {
    UUID userId = UUID.randomUUID();
    jdbc.update("INSERT INTO user_membership(user_id,tier,billing_interval,status,created_at,updated_at) VALUES (?, 'CHEF','NONE','ACTIVE',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)", userId);
    assertNull(service.reserve(userId));
  }

  private UUID member(String tier, String status, Instant paidUntil) {
    UUID userId = UUID.randomUUID();
    jdbc.update("INSERT INTO user_membership(user_id,tier,billing_interval,status,paid_until,created_at,updated_at) VALUES (?,?,'MONTHLY',?,?,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)",
        userId, tier, status, paidUntil == null ? null : Timestamp.from(paidUntil));
    return userId;
  }

  private UUID reward(UUID userId, String status, Instant expiresAt) {
    UUID id = UUID.randomUUID();
    jdbc.update("INSERT INTO gamification_reward_grant(id,user_id,reward_type,source_key,status,issued_at,expires_at,reserved_at) VALUES (?,?,'FREE_RECIPE_GENERATION',?,?,?,?,?)",
        id, userId, "week:" + id, status, Timestamp.from(Instant.now().minusSeconds(60)), Timestamp.from(expiresAt),
        "RESERVED".equals(status) ? Timestamp.from(Instant.now().minus(Duration.ofHours(2))) : null);
    return id;
  }

  private String rewardStatus(UUID id) {
    return jdbc.queryForObject("SELECT status FROM gamification_reward_grant WHERE id=?", String.class, id);
  }

  @Test
  void newUserGetsAFreeMembershipExactlyOnce() {
    UUID userId = UUID.randomUUID();
    service.ensureMembership(userId);
    service.ensureMembership(userId);
    assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM user_membership WHERE user_id=?", Integer.class, userId));
    assertEquals("FREE", jdbc.queryForObject("SELECT tier FROM user_membership WHERE user_id=?", String.class, userId));
  }

  @Test
  void activeCookerGetsTenDailyGenerations() {
    UUID userId = member("COOKER", "ACTIVE", Instant.now().plus(Duration.ofDays(10)));
    for (int i = 0; i < 10; i++) assertTrue(service.reserve(userId).periodKey().startsWith("COOKER_DAILY:"));
    assertNull(service.reserve(userId));
  }

  @Test
  void expiredCookerIsDowngradedToFreeAndUsesTheLifetimeQuota() {
    UUID userId = member("COOKER", "ACTIVE", Instant.now().minusSeconds(1));
    assertEquals("FREE_LIFETIME", service.reserve(userId).periodKey());
    assertEquals("FREE", jdbc.queryForObject("SELECT tier FROM user_membership WHERE user_id=?", String.class, userId));
    assertEquals("EXPIRED", jdbc.queryForObject("SELECT status FROM user_membership WHERE user_id=?", String.class, userId));
  }

  @Test
  void cancelledCookerWithFuturePaidUntilIsNotPaid() {
    UUID userId = member("COOKER", "CANCELLED", Instant.now().plus(Duration.ofDays(3)));
    assertEquals("FREE_LIFETIME", service.reserve(userId).periodKey());
  }

  @Test
  void promotionalRewardIsSpentBeforeTheRegularQuotaAndRedeemedOnCommit() {
    UUID userId = member("FREE", "ACTIVE", null);
    UUID reward = reward(userId, "AVAILABLE", Instant.now().plus(Duration.ofDays(5)));

    EntitlementService.QuotaReservation reservation = service.reserve(userId);
    assertEquals("PROMO_REWARD:" + reward, reservation.periodKey());
    assertEquals("RESERVED", rewardStatus(reward));
    assertTrue(jdbc.queryForList("SELECT * FROM recipe_quota_usage WHERE user_id=?", userId).isEmpty());

    service.commit(reservation);
    assertEquals("REDEEMED", rewardStatus(reward));
    service.commit(reservation);
    assertEquals("REDEEMED", rewardStatus(reward));
  }

  @Test
  void releasedPromotionalRewardBecomesAvailableAgain() {
    UUID userId = member("FREE", "ACTIVE", null);
    UUID reward = reward(userId, "AVAILABLE", Instant.now().plus(Duration.ofDays(5)));
    service.release(service.reserve(userId));
    assertEquals("AVAILABLE", rewardStatus(reward));
  }

  @Test
  void expiredRewardsAreIgnored() {
    UUID userId = member("FREE", "ACTIVE", null);
    reward(userId, "AVAILABLE", Instant.now().minusSeconds(5));
    assertEquals("FREE_LIFETIME", service.reserve(userId).periodKey());
  }

  @Test
  void staleReservedRewardsAreReturnedButFreshOnesAreKept() {
    UUID userId = member("FREE", "ACTIVE", null);
    UUID stale = reward(userId, "RESERVED", Instant.now().plus(Duration.ofDays(5)));
    UUID fresh = reward(userId, "RESERVED", Instant.now().plus(Duration.ofDays(5)));
    jdbc.update("UPDATE gamification_reward_grant SET reserved_at=? WHERE id=?", Timestamp.from(Instant.now()), fresh);
    service.releaseStalePromoReservations();
    assertEquals("AVAILABLE", rewardStatus(stale));
    assertEquals("RESERVED", rewardStatus(fresh));
  }

  @Test
  void commitOfARegularReservationIsANoOpAndReleaseNeverGoesNegative() {
    UUID userId = member("FREE", "ACTIVE", null);
    EntitlementService.QuotaReservation reservation = service.reserve(userId);
    service.commit(reservation);
    service.release(reservation);
    service.release(reservation);
    assertEquals(0, jdbc.queryForObject("SELECT used_count FROM recipe_quota_usage WHERE user_id=?", Integer.class, userId));
    service.release(null);
    service.commit(null);
  }

  @Test
  void concurrentReservationsNeverExceedTheQuota() throws Exception {
    var proxy = new ProxyFactory(new EntitlementService(jdbc));
    proxy.setProxyTargetClass(true);
    proxy.addAdvice(new TransactionInterceptor(new DataSourceTransactionManager(dataSource), new AnnotationTransactionAttributeSource()));
    EntitlementService transactional = (EntitlementService) proxy.getProxy();
    UUID userId = member("FREE", "ACTIVE", null);

    ExecutorService pool = Executors.newFixedThreadPool(12);
    CountDownLatch start = new CountDownLatch(1);
    AtomicInteger granted = new AtomicInteger();
    List<Future<?>> futures = new ArrayList<>();
    for (int i = 0; i < 12; i++) futures.add(pool.submit(() -> {
      start.await();
      if (transactional.reserve(userId) != null) granted.incrementAndGet();
      return null;
    }));
    start.countDown();
    for (Future<?> f : futures) f.get(30, TimeUnit.SECONDS);
    pool.shutdown();

    assertEquals(3, granted.get());
    assertEquals(3, jdbc.queryForObject("SELECT used_count FROM recipe_quota_usage WHERE user_id=?", Integer.class, userId));
  }
}
