-- Canonical ingredient dictionary and SQL-backed recipe discovery.
CREATE TABLE ingredient (
  id VARCHAR(80) PRIMARY KEY,
  canonical_name VARCHAR(120) NOT NULL,
  normalized_name VARCHAR(160) NOT NULL UNIQUE
);

CREATE TABLE ingredient_alias (
  id BIGSERIAL PRIMARY KEY,
  ingredient_id VARCHAR(80) NOT NULL REFERENCES ingredient(id),
  alias VARCHAR(160) NOT NULL,
  normalized_alias VARCHAR(160) NOT NULL UNIQUE,
  match_type VARCHAR(20) NOT NULL DEFAULT 'EXACT'
    CHECK (match_type IN ('EXACT', 'VARIANT')),
  confidence NUMERIC(4,3) NOT NULL DEFAULT 1.000
    CHECK (confidence > 0 AND confidence <= 1),
  enabled BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_ingredient_alias_ingredient ON ingredient_alias(ingredient_id) WHERE enabled = TRUE;

CREATE TABLE recipe_catalog (
  id VARCHAR(160) PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  category VARCHAR(20) NOT NULL CHECK (category IN ('MEAL', 'DESSERT', 'DRINK')),
  servings INTEGER NOT NULL CHECK (servings > 0),
  estimated_total_minutes INTEGER NOT NULL CHECK (estimated_total_minutes > 0),
  active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_recipe_catalog_category_active ON recipe_catalog(category, active, title);

CREATE TABLE recipe_ingredient (
  id BIGSERIAL PRIMARY KEY,
  recipe_id VARCHAR(160) NOT NULL REFERENCES recipe_catalog(id) ON DELETE CASCADE,
  ingredient_id VARCHAR(80) NOT NULL REFERENCES ingredient(id),
  quantity NUMERIC(12,3) NOT NULL CHECK (quantity > 0),
  unit VARCHAR(30) NOT NULL,
  preparation VARCHAR(160),
  UNIQUE (recipe_id, ingredient_id)
);
CREATE INDEX idx_recipe_ingredient_ingredient_recipe ON recipe_ingredient(ingredient_id, recipe_id);
CREATE INDEX idx_recipe_ingredient_recipe ON recipe_ingredient(recipe_id);

